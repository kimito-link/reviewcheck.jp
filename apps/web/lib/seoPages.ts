import type { FaqItem } from "@reviewcheck/config";
import { COMMON_FAQ } from "@reviewcheck/config";

export interface SeoServicePageData {
  /** 末尾スラッシュ付きパス */
  slug: string;
  metaTitle: string;
  metaDescription: string;
  breadcrumbName: string;
  h1: string;
  lead: string;
  serviceType: string;
  /** 想定される症状・お悩み */
  symptoms: string[];
  /** 診断・対応内容 */
  included: { title: string; desc: string }[];
  /** 対応の流れ */
  steps: string[];
  faq: FaqItem[];
  /** ヒーローで強調するCTAキー（CTAS） */
  primaryCtaKeys: string[];
  /**
   * 検索意図に言葉を合わせる「第一声」（型の中核：検索語ごとに第一声と着地を設計）。
   *  - searcher: どんな状況・心理で検索した人かを言い当てる一言（共感のアイブロウ）
   *  - firstVoice: 煽らず寄り添う最初の一言（保証しない・むやみに消さない等の正直さを含む）
   */
  intent?: { searcher: string; firstVoice: string };
  /**
   * このLPの相談をどのLINE窓口へ流すか（topic→チャネルで自動振り分け）。
   * 風評・口コミ系は既定（repute）、IT系は it 窓口へ。未指定は既定。
   */
  lineTopic?: string;
  /**
   * サービス分類。"it" のLPは口コミ診断導線ではなくLINE相談を主導線にし、
   * 料金は専用カード（pricing）または注記（pricingNote）を表示する。
   * 未指定は "review"（口コミ・風評）。
   */
  category?: "review" | "it";
  /** カテゴリ "it" 等で表示する専用料金カード（積み上げ式・松竹梅）。 */
  pricing?: {
    name: string;
    price: string;
    priceNote?: string;
    description: string;
    /** 本命（竹）を強調 */
    featured?: boolean;
  }[];
  /** 料金の補足注記（pricing と併記、または単独で表示）。 */
  pricingNote?: string;
  /**
   * 実績・保証の数値バンド（④信頼性の「証拠」）。
   * 事実として確認できるものだけを入れる（捏造しない）。主にIT系で使用。
   */
  proofStats?: { value: string; label: string }[];
  /** 実績バンドの注記（保証しない旨など）。 */
  proofNote?: string;
  /**
   * 実際のお客様の声（④信頼性の「証拠」）。
   * 必ず本物の許諾済みの声だけを入れる（創作しない）。データが来たら表示される。
   */
  testimonials?: { quote: string; author: string }[];
}

const pick = (questions: string[]): FaqItem[] =>
  COMMON_FAQ.filter((f) => questions.includes(f.question));

